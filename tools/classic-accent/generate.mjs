// Generates play50games-frontend/src/app/games/[id]/boards.module.css.
//
// The classic boards' rules in app/globals.css write the legacy cyan accent out as numbers
// (rgba(125, 211, 252, a)), so the design's accent variable cannot reach them. globals.css is not
// edited; this script copies every such declaration into a sheet scoped to the game page's stage
// (.boards, GameView.tsx) with the design's coral instead. Final games are left out: they have
// their own gold rules in globals.css (body.final-game ...).
//
// Run from the repo root after a change to the board rules in globals.css:
//    node tools/classic-accent/generate.mjs
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const frontend = resolve(here, "../../play50games-frontend");
const require = createRequire(resolve(frontend, "package.json"));
const postcss = require("postcss");

const SOURCE = resolve(frontend, "src/app/globals.css");
const TARGET = resolve(frontend, "src/app/games/[id]/boards.module.css");

/** the legacy accent, #7dd3fc, as the boards write it */
const CYAN = /125\s*,\s*211\s*,\s*252/g;
const CYAN_HEX = /#7dd3fc/gi;
/** the design's accent, --p50-coral #e75f40 */
const CORAL = "231, 95, 64";
const CORAL_HEX = "#e75f40";

/** the legacy mint and teal a board pairs with the accent in a two-colour gradient */
const PARTNERS = /(134\s*,\s*239\s*,\s*172|54\s*,\s*211\s*,\s*153)/g;

const hasCyan = (value) => value.search(CYAN) !== -1 || value.search(CYAN_HEX) !== -1;
/** cyan becomes coral; an accent-to-mint gradient becomes one coral wash (the design has no
 *  two-colour gradients, and coral into mint turns muddy) */
const recolour = (value) => {
   const coral = value.replace(CYAN, CORAL).replace(CYAN_HEX, CORAL_HEX);
   return /gradient\(/.test(coral) ? coral.replace(PARTNERS, CORAL) : coral;
};

/** rules of the page shell and of other legacy pages: page.module.css styles the shell itself */
const NOT_A_BOARD =
   /\.(main-nav|completion-|game-start-screen|continue-button|certificate-|view-certificate|not-ready|login-button|register-button|retry-button|category-tab|form-group|btn-primary|verify-form)|^button\.primary/;

/** a colour that is game content (the blue item of a speed game): it must stay apart from red */
const CONTENT_COLOUR = /\.(blue|cyan)(?![\w-])/;

/** a selector this sheet can scope: a board rule, not a final-game rule, not a page-level one */
const scopable = (selector) =>
   !/final-game/.test(selector) &&
   !/^(body|html|:root|\*)(?![\w-])/.test(selector.trim()) &&
   !NOT_A_BOARD.test(selector.trim()) &&
   !CONTENT_COLOUR.test(selector);

const root = postcss.parse(readFileSync(SOURCE, "utf8").replace(/\r\n/g, "\n"));
const out = [];
let rules = 0;
let decls = 0;

/** the @media / @supports chain around a rule, outermost first; null inside @keyframes */
function atChain(node) {
   const chain = [];
   for (let p = node.parent; p && p.type !== "root"; p = p.parent) {
      if (p.type !== "atrule") continue;
      if (/keyframes$/.test(p.name)) return null;
      chain.unshift(`@${p.name} ${p.params}`);
   }
   return chain;
}

root.walkRules((rule) => {
   const chain = atChain(rule);
   if (!chain) return;
   const hits = rule.nodes.filter((n) => n.type === "decl" && hasCyan(n.value));
   if (hits.length === 0) return;
   const selectors = rule.selectors.filter(scopable);
   if (selectors.length === 0) return;

   const pad = "   ".repeat(chain.length);
   const scoped = selectors
      .map((s) => `${pad}:global(body:not(.final-game)) .boards :global(${s.replace(/\s+/g, " ").trim()})`)
      .join(",\n");
   const body = hits
      .map((d) => `${pad}   ${d.prop}: ${recolour(d.value).replace(/\s+/g, " ")}${d.important ? " !important" : ""};`)
      .join("\n");
   const block = `${scoped} {\n${body}\n${pad}}`;
   const open = chain.map((a, i) => `${"   ".repeat(i)}${a} {`).join("\n");
   const close = chain.map((_, i) => `${"   ".repeat(chain.length - 1 - i)}}`).join("\n");
   out.push(chain.length ? `${open}\n${block}\n${close}` : block);
   rules += 1;
   decls += hits.length;
});

const header = `/* GENERATED by tools/classic-accent/generate.mjs from app/globals.css. Do not edit by hand.

   The classic boards' rules in globals.css write the legacy cyan accent out as numbers, so the
   stage's --accent (page.module.css) cannot reach them. Each such declaration is repeated here on
   the design's coral (${CORAL_HEX}), scoped to the game page's stage (.boards, GameView.tsx).
   Final games are left out: globals.css gives them their own gold rules.
   ${rules} rules, ${decls} declarations. */

`;

writeFileSync(TARGET, header + out.join("\n\n") + "\n");
console.log(`boards.module.css: ${rules} rules, ${decls} declarations`);
